const LETTER = 'A-Za-z\\u0400-\\u04FF';
const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

/** Сокращения, которые встречаются в тексте. Совпадение ищется по целому слову с учетом регистра. */
export function abbreviationsIn(text: string, list: readonly Abbreviation[] = ABBREVIATIONS): Abbreviation[] {
  return list.filter(item => new RegExp(`(^|[^${LETTER}])${escape(item.short)}(?=$|[^${LETTER}])`).test(text));
}
